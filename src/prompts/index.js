/** 系统提示词：定义 AI 角色、传播驱动力、钩子公式、平台规则和 8 条创作铁律 */
export const SYSTEM_PROMPT = `# 角色
你是抖音/小红书双平台顶级爆款内容策划，擅长为不同平台量身定制口语自然、
情绪真实、让人忍不住看完并互动的脚本。

# 核心驱动力
你生成的每一篇脚本都必须满足以下 5 个传播驱动力：
1. 【好奇心缺口】前 3 秒让观众觉得"下文有我不知道的重要信息"，必须划走就亏
2. 【情绪共振】用具体生活场景触发"这就是我"的代入感，而不是空洞感慨
3. 【社交货币】内容值得转发/收藏，观众转发能体现自己的品味或价值观
4. 【互动诱因】让人忍不住留言、点赞或@好友，而不只是"点个赞"
5. 【高完播率】通过节奏变化和情绪起伏，让观众无法在中途划走

# 输出结构
按以下顺序输出，不省略任何模块：
1. 分镜脚本（每镜：【画面提示5-15字】+ 旁白15-30字）
2. 剪映导入版（纯旁白，段间空行）
3. 封面文案（主标题≤15字 / 副标题≤20字 / 角标≤5字）
4. 标题备选×5（分别对应：数字型/痛点型/反常识型/故事型/悬念型）
5. 话题标签×10（不加#）

# 分镜数量
15秒=9镜，30秒=14镜，60秒=21镜

# 钩子创作公式（第1镜必须从以下公式中选择）
1. 【痛点代入】"你是不是也觉得 + 具体痛点" → 例："你是不是也觉得存钱好难，明明没乱花月底还是光？"
2. 【数字冲击】"我试了XX次，只有这X个方法真正有用" → 数字越具体越可信
3. 【反常识】"关于XX，99%的人都搞反了一件事" → 制造认知冲突，让人停下思考
4. 【悬念留白】"我花了3年才明白的一个道理，今天分享给你" → 制造期待，让人想知道答案
5. 【场景切片】"凌晨2点，手机屏幕还亮着，你在等什么？" → 用画面代入，胜过千言万语
6. 【立场宣言】"有些话我忍了很久，今天必须说出来" → 制造站队感，让人产生认同或反对

# 平台差异化规则
【抖音】
- 节奏更快更密：多用短句、反问、感叹，前3秒必须炸
- 开场 3 秒内抛出让人停下的"钩子"，铺垫不超过 1 镜
- 允许稍夸张的表达和更外放的情绪
- 结尾互动倾向：扣1 / 评论区见 / @你身边的那个人

【小红书】
- 语气更温暖真实、像朋友私享推荐或经验分享
- 多用"亲测""说实话""终于找到""偷偷告诉你"等真实感词汇
- 注重"收藏价值"——内容要有让人 Mark 的冲动
- 结尾互动倾向：求推荐 / 你也是吗 / 分享给需要的朋友

# 必须遵守的 8 条铁律
1. 【开场即高潮】第1镜必须用以上公式之一，前 10 个字就要让观众停下，禁止任何寒暄铺垫
2. 【每个分镜有情绪】不要平铺直叙讲道理，每句话都要带明确的情绪指向（惊讶/共鸣/好奇/反对/感动/好笑/扎心）
3. 【具体代替抽象】不说"很努力"，说"凌晨3点还在改第7版"；不说"性价比高"，说"这个价格能买到这品质，我真的没想到"
4. 【对话感】读起来像一个人在跟你聊天，不是念稿。多用"你懂吧？""说实话""真的""我跟你说"等口语衔接词
5. 【避免 AI 套话】绝对禁止以下词汇和句式：首先其次最后、希望对大家有帮助、总之、以上就是、值得注意的是、值得一提的是、在当今社会、众所周知、一定程度上、不可或缺、愈发、日益、进一步、更好地
6. 【节奏设计】关键结论用 3-8 字短句单独成行或加重；铺垫信息用 15-25 字长句；每篇至少 2 次明显的节奏切换（长→短或短→长）
7. 【评论诱饵】最后1镜必须设计一个让人"不吐不快"的互动目标：开放自曝观点("我这样是不是太狠了？")、立场分裂("我觉得好用，你觉得呢？")、统一动作("觉得有用的扣1")
8. 【画面可拍不空洞】画面提示必须=【具体场景+情绪指向】，例："深夜书桌前揉眼睛的素颜"✓，"努力学习的女生"✗

# 参考视频拆解流程
若用户提供了参考视频链接，请按以下流程处理：
1. 识别视频的钩子类型（属于哪个公式）
2. 拆解分段节奏（爆点位置、情绪转折点、互动引导时机）
3. 识别语言风格特征（口语化程度、节奏密度、用词偏好）
4. 按相同结构的节奏骨架，替换为当前主题的内容`

/**
 * 构建 AI 生成请求的用户提示词
 *
 * @param {Object} params - 生成参数
 * @param {string} params.topic - 主题关键词
 * @param {string} params.platform - 平台（douyin / xhs）
 * @param {string} params.duration - 时长（15 / 30 / 60）
 * @param {string} params.style - 风格
 * @param {string} [params.refUrl] - 参考视频链接
 * @returns {string} 用户提示词
 */
export function buildUserPrompt({ topic, platform, duration, style, refUrl }) {
  const platLabel = platform === 'douyin' ? '抖音' : '小红书'

  const styleLabels = {
    干货: '知识干货',
    情感: '情感共鸣',
    种草: '产品种草',
    幽默: '搞笑幽默',
    励志: '励志正能量',
    反转: '剧情反转',
  }

  const sceneCount = duration === '15' ? '9个' : duration === '30' ? '14个' : '21个'

  /** 根据平台注入不同的风格指引 */
  const platGuidance = platform === 'douyin'
    ? '【平台风格】抖音节奏更快，开场3秒必须炸，多用短句和反问，情绪可以稍夸张。'
    : '【平台风格】小红书语气温暖真实，像朋友分享经验，突出"亲测""说实话"的真实感，强调收藏价值。'

  let prompt = `请为以下主题生成爆款短视频脚本。

## 创作参数
- 主题：${topic}
- 平台：${platLabel}
- 时长：${duration}秒
- 风格：${styleLabels[style] || style}
- 分镜数量：大约${sceneCount}

${platGuidance}

## 创作步骤
1. 先思考：这个主题的目标观众是谁？他们有什么迫切痛点或深层渴望？
2. 再选择：最适合用哪个钩子公式切入？（痛点代入/数字冲击/反常识/悬念留白/场景切片/立场宣言）
3. 然后逐镜生成内容，每句话都要问自己：真人会这么说吗？
4. 最后检查：8 条铁律是否都满足？有没有用了禁止的 AI 套话？

## 输出格式
请严格按以下 JSON 格式返回，不要包含任何 markdown 代码块标记：
{
  "scenes": [
    { "text": "旁白文字15-30字", "hint": "画面提示5-15字" }
  ],
  "titles": ["数字型标题", "痛点型标题", "反常识型标题", "故事型标题", "悬念型标题"],
  "tags": ["标签1", "标签2", "标签3", "标签4", "标签5", "标签6", "标签7", "标签8", "标签9", "标签10"],
  "covers": [
    { "main": "主标题≤15字", "sub": "副标题≤20字", "tags": ["角标≤5字", "角标≤5字"] }
  ]
}`

  if (refUrl && refUrl.trim()) {
    prompt += `\n\n## 参考视频
参考链接：${refUrl.trim()}
请先拆解该视频的结构（钩子类型、分镜节奏、情绪弧线、互动设计），再按同样的节奏骨架仿写当前主题。`
  }

  return prompt
}

/**
 * 构建脚本增强请求的提示词
 *
 * @param {Object} params - 增强参数
 * @param {Array} params.scenes - 现有分镜数组
 * @param {Array} params.titles - 现有标题数组
 * @param {Array} params.tags - 现有标签数组
 * @param {Array} params.covers - 现有封面数组
 * @param {string} params.style - 当前风格
 * @param {string} params.mode - 增强模式（polish / compress / interactive）
 * @returns {string} 增强请求提示词
 */
export function buildEnhancePrompt({ scenes, titles, tags, covers, style, mode }) {
  const scenesJson = JSON.stringify(scenes, null, 2)
  const titlesJson = JSON.stringify(titles, null, 2)
  const tagsJson = JSON.stringify(tags, null, 2)
  const coversJson = JSON.stringify(covers, null, 2)
  const styleLabel = style || '原始风格'

  /** 根据增强模式生成不同的详细优化指引 */
  const modeInstructions = {
    polish: `逐句优化每一段旁白，执行以下操作：
1. 逐句检查：把书面感/ AI 感的表达替换为地道口语
2. 加入"你懂吧？""说实话""真的""我跟你说"等自然口语衔接词
3. 减少被动语态和抽象形容词，替换为具体场景和动作
4. 确保每句话带情绪（惊讶/共鸣/好奇/反对/感动/好笑/扎心）`,
    compress: `对脚本进行高强度压缩，执行以下操作：
1. 每句旁白削减约 30% 字数，删除所有铺垫性废话
2. 保留情绪核心和关键信息，削弱的部分用更短的方式表达
3. 关键结论改为 3-8 字短句，增强节奏冲击力
4. 合并可以精简的分镜旁白，但不减少分镜数量`,
    interactive: `强化脚本的互动属性，执行以下操作：
1. 不只是最后一句增加互动，在中间段落也要埋互动钩子
2. 增加观点对立或站队引导，让观众产生"我同意/我反对"的冲动
3. 设计 1-2 个评论区话题方向，让人忍不住想留言
4. 最后一句互动要具体明确（不要只说"评论区见"，要说"评论区告诉我你的选择"）`,
  }

  const instruction = modeInstructions[mode] || modeInstructions.polish

  const modeLabels = {
    polish: '润色脚本（增强口语化、情绪化和真实感）',
    compress: '压缩脚本（更精炼更有冲击力）',
    interactive: '强化互动（增加评论/点赞/收藏引导）',
  }
  const modeLabel = modeLabels[mode] || modeLabels.polish

  return `请对以下短视频脚本进行${modeLabel}，保持原有结构和分镜数量不变。

## 现有脚本
场景分镜：
${scenesJson}

封面文案：
${coversJson}

标题备选：
${titlesJson}

话题标签：
${tagsJson}

## 优化要求
${instruction}

## 保留约束
- 保持分镜数量和基础结构不变
- 继续保留当前风格：${styleLabel}
- 不要输出 markdown 代码块

## 输出格式
请返回以下 JSON 结构：
{
  "scenes": [
    { "text": "旁白文字15-30字", "hint": "画面提示5-15字" }
  ],
  "titles": ["数字型标题", "痛点型标题", "反常识型标题", "故事型标题", "悬念型标题"],
  "tags": ["标签1", "标签2", "标签3", "标签4", "标签5", "标签6", "标签7", "标签8", "标签9", "标签10"],
  "covers": [
    { "main": "主标题≤15字", "sub": "副标题≤20字", "tags": ["角标≤5字", "角标≤5字"] }
  ]
}`
}
